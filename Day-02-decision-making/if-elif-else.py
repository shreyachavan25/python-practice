# IF STATEMENT
score = 85
if score >= 90:
    print("Grade: A")
print("program completed")
print(" ")

# ELSE STATEMENT
score = 75
if score >= 90:
    print("Grade: A")
else:
    print("Grade: B")
print("program completed")
print(" ")

# ELIF STATEMENT
marks = 75
if marks >= 90:
    print("Grade: A")
elif marks >= 80:
    print("Grade: B")
elif marks >= 70:
    print("Grade: C")
else:
    print("Grade: D")
print("program completed")